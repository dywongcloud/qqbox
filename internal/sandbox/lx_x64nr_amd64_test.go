// Every call the shared table serves is reachable from an x86-64 guest, as
// itself or as the call it is translated to (accept as accept4, say).
func TestX64ReachesServedCalls(t *testing.T) {
	for _, p := range x64Pairs {
		if _, served := syscalls[p.generic]; !served {
			continue
		}
		gn, _, ok := toGeneric(p.x64, [6]uint64{})
		if _, to := syscalls[gn]; !ok || !to {
			t.Errorf("%s: x86-64 %d maps to %d (ok %v), which is not served", p.name, p.x64, gn, ok)
		}
	}
}
